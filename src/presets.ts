function build(mode: Mode, kind: OutKind | null, seeds: Seed[]): Item[] {
  return seeds.map(([emoji, name, category, tags, level]) => ({
    id: uid(),
    mode,
    kind,
    name,
    emoji,
    category,
    level: level ?? 0,
    tags,
    memo: '',
  }));
}

export function presetItems(): Item[] {
  return [...build('home', null, HOME), ...build('out', 'genre', OUT_GENRE), ...build('out', 'shop', OUT_SHOP)];
}

